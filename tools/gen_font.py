def glyph_columns(ch):
    rows = GLYPHS[ch]
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    cols = []
    for x in range(5):
        byte = 0
        for y in range(7):
            if rows[y][x] == '#':
                byte |= 1 << y
        cols.append(byte)
    cols.append(0)  # разделитель
    return cols


def font_table():
    """Список из COUNT*COLS байтов в порядке адресов ROM."""
    table = []
    for code in range(FIRST, FIRST + COUNT):
        table.extend(glyph_columns(chr(code)))
    return table


def render_column(code, col):
    """Эталонная модель FONT_RENDER — то же, что делает аппаратура."""
    code &= 0xFFFF
    col &= 0xFFFF
    if 0x60 <= code <= 0x7E:
        code -= 0x20
    if code < FIRST or code >= FIRST + COUNT or col >= COLS:
        return 0
    return font_table()[(code - FIRST) * COLS + col]


def main():
    assert len(GLYPHS) == COUNT, f"нужно {COUNT} глифов, есть {len(GLYPHS)}"
    table = font_table()
    if len(sys.argv) > 2 and sys.argv[1] == "--expect":
        # эталон для tb/tb_font.v: все коды 0..127 x столбцы 0..7
        with open(sys.argv[2], "w") as f:
            for code in range(128):
                for col in range(8):
                    f.write(f"{render_column(code, col):02x}\n")
        print(f"{sys.argv[2]}: эталон 128 x 8")
    elif len(sys.argv) > 1:
        with open(sys.argv[1], "w") as f:
            for i, b in enumerate(table):
                f.write(f"{b:02x}\n")
        print(f"{sys.argv[1]}: {len(table)} байт")
    else:
        for code in range(FIRST, FIRST + COUNT):
            cols = glyph_columns(chr(code))
            print(repr(chr(code)))
            for y in range(7):
                print("  " + "".join("#" if c >> y & 1 else "." for c in cols))


if __name__ == "__main__":
    main()
